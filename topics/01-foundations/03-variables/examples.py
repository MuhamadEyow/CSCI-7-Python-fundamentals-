"""Commented examples: variables and basic data types."""

# A string stores text.
student_name = "Muhamad"

# An integer stores a whole number.
weekly_study_hours = 7

# A float stores a decimal number.
course_progress = 0.0

# A Boolean stores either True or False.
is_enrolled = True

# None represents the absence of a value.
final_grade = None

print(f"Student: {student_name} ({type(student_name).__name__})")
print(f"Weekly hours: {weekly_study_hours} ({type(weekly_study_hours).__name__})")
print(f"Progress: {course_progress} ({type(course_progress).__name__})")
print(f"Enrolled: {is_enrolled} ({type(is_enrolled).__name__})")
print(f"Final grade: {final_grade} ({type(final_grade).__name__})")
